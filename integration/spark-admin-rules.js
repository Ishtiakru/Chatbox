// Experimental Spark-only rules, tested with synthetic identities, not deployed.
import { readFileSync } from 'node:fs';
import { after, before, beforeEach, test } from 'node:test';
import { initializeTestEnvironment, assertFails, assertSucceeds } from '@firebase/rules-unit-testing';
import { collection, doc, getDoc, getDocs, setDoc, updateDoc, deleteDoc, serverTimestamp } from 'firebase/firestore';
import assert from 'node:assert/strict';
import { createSparkAdminService } from '../src/spark-admin-data.js';
let env;
const time = () => Math.floor(Date.now() / 1000);
const claims = (email, options = {}) => ({email, email_verified: options.verified ?? true, firebase: {sign_in_provider: options.provider ?? 'google.com'}, auth_time: options.authTime ?? time()});
before(async () => {
  if (!process.env.FIRESTORE_EMULATOR_HOST) throw new Error('Use an emulator.');
  env = await initializeTestEnvironment({ projectId:'demo-chatbox', firestore:{rules:readFileSync(process.env.CHATBOX_TEST_RULES_FILE || 'firestore.spark-admin.rules','utf8')} });
});
beforeEach(async () => { await env.clearFirestore(); });
after(async () => { if (env) await env.cleanup(); });
const as = (uid, email, opts) => env.authenticatedContext(uid, claims(email,opts)).firestore();
const adminDoc = db => doc(db,'sparkAdmin','current');
const delegation = (db,email) => doc(db,'sparkDelegations',email);
const settings = db => doc(db,'settings','sparkPublic');
const bootstrap = (db, uid, email) => setDoc(adminDoc(db), {uid,email,pendingEmail:'',createdAt:serverTimestamp(),updatedAt:serverTimestamp()});
const invite = (db,email,uid='owner') => setDoc(delegation(db,email),{email,uid:'',invitedBy:uid,status:'invited',createdAt:serverTimestamp(),updatedAt:serverTimestamp()});
const welcome = (db,uid) => setDoc(settings(db),{welcome:'Hello',updatedAt:serverTimestamp(),updatedBy:uid});
const accept = (db,email,uid) => updateDoc(delegation(db,email),{uid,status:'active',updatedAt:serverTimestamp()});
const revoke = (db,email) => updateDoc(delegation(db,email),{status:'revoked',updatedAt:serverTimestamp()});
test('only the verified original Google account may bootstrap, and ownership cannot be transferred', async () => {
  await assertFails(bootstrap(as('evil','evil@gmail.com'),'evil','evil@gmail.com'));
  await assertFails(bootstrap(as('bad','ishtiakahmedru@gmail.com',{verified:false}),'bad','ishtiakahmedru@gmail.com'));
  await assertFails(bootstrap(as('bad2','ishtiakahmedru@gmail.com',{provider:'password'}),'bad2','ishtiakahmedru@gmail.com'));
  await assertFails(bootstrap(as('old','ishtiakahmedru@gmail.com',{authTime:time()-400}),'old','ishtiakahmedru@gmail.com'));
  const owner = as('owner','ishtiakahmedru@gmail.com');
  await assertSucceeds(bootstrap(owner,'owner','ishtiakahmedru@gmail.com'));
  await assertFails(bootstrap(as('second','ishtiakahmedru@gmail.com'),'second','ishtiakahmedru@gmail.com'));
  await assertFails(updateDoc(adminDoc(owner),{uid:'other',email:'other@gmail.com',updatedAt:serverTimestamp()}));
  await assertFails(deleteDoc(adminDoc(owner)));
});
test('only owner or active delegate can change bounded public welcome', async () => {
  const owner=as('owner','ishtiakahmedru@gmail.com'), outsider=as('outsider','other@gmail.com');
  await bootstrap(owner,'owner','ishtiakahmedru@gmail.com');
  await assertSucceeds(welcome(owner,'owner'));
  await assertSucceeds(getDoc(settings(outsider)));
  await assertFails(welcome(as('owner','ishtiakahmedru@gmail.com',{authTime:time()-400}),'owner'));
  await assertFails(welcome(outsider,'outsider'));
  await assertFails(setDoc(settings(owner),{welcome:'x'.repeat(161),updatedAt:serverTimestamp(),updatedBy:'owner'}));
  await assertFails(setDoc(settings(owner),{welcome:'Hello',updatedAt:serverTimestamp(),updatedBy:'outsider'}));
  await assertFails(setDoc(settings(owner),{welcome:'Hello',updatedAt:serverTimestamp(),updatedBy:'owner', extra:true}));
});
test('delegation requires owner invitation and verified recipient acceptance, retains owner access, and cannot be re-delegated', async () => {
  const owner=as('owner','ishtiakahmedru@gmail.com'), target=as('target','target@gmail.com'), third=as('third','third@gmail.com');
  await bootstrap(owner,'owner','ishtiakahmedru@gmail.com');
  await assertFails(getDoc(adminDoc(third)));
  await assertFails(invite(third,'third@gmail.com','third'));
  await assertFails(invite(as('owner','ishtiakahmedru@gmail.com',{authTime:time()-400}),'target@gmail.com'));
  await assertFails(invite(as('owner','ishtiakahmedru@gmail.com',{authTime:time()+400}),'target@gmail.com'));
  await assertFails(invite(owner,'target@example.com'));
  await assertFails(invite(owner,'ishtiakahmedru@gmail.com'));
  await assertSucceeds(invite(owner,'target@gmail.com'));
  await assertFails(getDoc(delegation(third,'target@gmail.com')));
  await assertFails(getDocs(collection(target,'sparkDelegations')));
  await assertSucceeds(getDocs(collection(owner,'sparkDelegations')));
  await assertSucceeds(getDoc(delegation(target,'target@gmail.com')));
  await assertFails(welcome(target,'target'));
  await assertFails(accept(third,'target@gmail.com','third'));
  await assertFails(accept(as('target','target@gmail.com',{verified:false}),'target@gmail.com','target'));
  await assertFails(accept(as('target','target@gmail.com',{provider:'password'}),'target@gmail.com','target'));
  await assertFails(accept(as('target','target@gmail.com',{authTime:time()-400}),'target@gmail.com','target'));
  await assertFails(accept(target,'target@gmail.com','third'));
  await assertSucceeds(accept(target,'target@gmail.com','target'));
  await assertSucceeds(welcome(target,'target'));
  await assertSucceeds(welcome(owner,'owner'));
  await assertFails(welcome(as('fake-uid','target@gmail.com'),'fake-uid'));
  await assertFails(invite(target,'third@gmail.com','target'));
  await assertFails(revoke(target,'target@gmail.com'));
});
test('owner revocation is effective immediately; re-invitation requires fresh acceptance', async () => {
  const owner=as('owner','ishtiakahmedru@gmail.com'), target=as('target','target@gmail.com');
  await bootstrap(owner,'owner','ishtiakahmedru@gmail.com');
  await invite(owner,'target@gmail.com'); await accept(target,'target@gmail.com','target');
  await assertSucceeds(revoke(owner,'target@gmail.com'));
  await assertFails(welcome(target,'target'));
  await assertFails(accept(target,'target@gmail.com','target'));
  await assertSucceeds(updateDoc(delegation(owner,'target@gmail.com'),{uid:'',invitedBy:'owner',status:'invited',updatedAt:serverTimestamp()}));
  await assertFails(welcome(target,'target'));
  await assertSucceeds(accept(target,'target@gmail.com','target'));
  await assertSucceeds(welcome(target,'target'));
  await assertSucceeds(revoke(owner,'target@gmail.com'));
  await assertFails(deleteDoc(delegation(owner,'target@gmail.com')));
});
test('Spark client service completes owner and delegate flow using synthetic verified accounts', async () => {
  const owner={uid:'owner',email:'ishtiakahmedru@gmail.com'}, target={uid:'target',email:'target@gmail.com'};
  const ownerApi=createSparkAdminService(as(owner.uid,owner.email));
  const targetApi=createSparkAdminService(as(target.uid,target.email));
  assert.deepEqual(await ownerApi.getSparkAdminStatus(owner),{status:'authorized',role:'owner'});
  assert.deepEqual(await targetApi.getSparkAdminStatus(target),{status:'forbidden',role:''});
  await assert.rejects(ownerApi.inviteSparkDelegate(owner,target.email,false));
  await ownerApi.inviteSparkDelegate(owner,target.email,true);
  assert.equal((await ownerApi.listSparkDelegations())[0].status,'invited');
  assert.deepEqual(await targetApi.getSparkAdminStatus(target),{status:'invited',role:'delegate'});
  await targetApi.acceptSparkDelegation(target,true);
  assert.deepEqual(await targetApi.getSparkAdminStatus(target),{status:'authorized',role:'delegate'});
  await targetApi.applySparkWelcome(target,'welcome: Hello',true);
  const bangla='স্বাগত বার্তাটি “সবাইকে স্বাগতম” করে দাও';
  await assert.rejects(targetApi.applySparkWelcome(target,bangla,false));
  await targetApi.applySparkWelcome(target,bangla,true);
  assert.equal((await getDoc(settings(as(owner.uid,owner.email)))).data().welcome,'সবাইকে স্বাগতম');
  await assert.rejects(targetApi.applySparkWelcome(target,'change admin to "evil"',true));
  await assert.rejects(targetApi.inviteSparkDelegate(target,'other@gmail.com',true));
  await ownerApi.revokeSparkDelegate(target.email,true);
  assert.deepEqual(await targetApi.getSparkAdminStatus(target),{status:'forbidden',role:''});
  await assert.rejects(targetApi.applySparkWelcome(target,'welcome: denied',true));
  assert.deepEqual(await ownerApi.getSparkAdminStatus(owner),{status:'authorized',role:'owner'});
});
